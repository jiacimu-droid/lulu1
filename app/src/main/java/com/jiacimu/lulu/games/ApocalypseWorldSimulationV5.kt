package com.jiacimu.lulu.games

private val apocalypseCityPopulationV5 = mapOf(
    "linjiang" to "约320万",
    "xinchuan" to "约190万",
    "hailing" to "约220万",
    "lanshan" to "约80万",
    "yunqi" to "约160万",
    "baiyu" to "约90万",
)

/**
 * Hidden world bible for the showrunner. This is deliberately richer than the
 * player-facing world archive: the director needs a coherent simulation while
 * the player should only learn what can actually be observed or verified.
 */
internal fun apocalypseWorldSimulationBibleV5(save: ApocalypseV3Save): String = buildString {
    appendLine("【隐藏世界设定圣经｜总导演知道，玩家不自动知道】")
    appendLine("目标：把东澜写成一个在灾难中真实运转、真实损坏、真实适应的现代社会，而不是为了剧情临时生成的布景。所有事件先经过地理、人口、基础设施、时间、物流和人类行为检查，再进入剧情。")
    appendLine("当前故事时标=${apocalypseDayLabelV5(save.director.dayIndex)} ${apocalypseClockLabelV5(save.director.clockMinutes)}；当前天气=${save.director.weather} ${save.director.temperatureC}℃；当前地点=${save.director.location}。")
    appendLine()

    appendLine("【世界尺度】")
    appendLine("东澜六市只是当前故事的核心区域，不是整个世界。六市与周边县镇构成约一千零八十万人口的连续都市—农业—港口经济圈；国家其他地区、邻近省域和海外社会都真实存在，并会通过广播、难民、卫星、航运和残余网络产生影响。")
    appendLine("灾难是广域乃至全球性的，但严重度、发生时刻和恢复能力不完全同步。禁止第一天就一句话宣布‘全世界政府都没了’，也禁止后期凭空出现一个完全正常、资源无限的外部世界。")
    appendLine("技术基线接近现代2020年代：智能手机、移动支付、高铁、高速公路、5G/光纤、无人机、电动车、现代医院和工业体系普遍存在；生态修复载体是少数领先技术。赤潮发生前不存在随手可得的科幻黑科技。")
    appendLine("社会与武器基线接近现代东亚城市：民间枪械稀少，制式枪械、弹药和防护装备主要来自警务、军队、正规安保及少量特殊单位，因此枪械与弹药长期都应是战略资源，不能人人自动掏出步枪。")
    appendLine()

    appendLine("【六市人口与功能】")
    apocalypseWorldCitiesV5().forEach { city ->
        appendLine("${city.name}｜灾前常住人口${apocalypseCityPopulationV5[city.id] ?: "未细分"}｜${city.direction}｜${city.summary}｜主要系统性风险：${city.hazard}")
    }
    appendLine("人口不是无限NPC池。导演需要维护隐含的人口账：疏散、伤亡、迁移、聚居都必须从原有人口与交通能力中来；一个几百人的据点已经需要稳定供水、厕所、厨房、医疗、值守和垃圾处理，几千人的聚居地必然出现组织结构和供应链。")
    appendLine()

    appendLine("【自然地理与水系】")
    appendLine("东澜总体西高东低。岚山山地是主要集水区，东江从西北山地和水库体系向东南流，经临江平原后进入海陵河口；云栖湖区与西南农业水网通过支流补给东江下游。白榆位于东北较高地势，是能源、林业和部分水源涵养区。")
    appendLine("河流、桥梁、隧道和山口是硬地理，不会因为剧情需要移动。跨江桥断一座会真实改变物流半径；山体滑坡封隧道会把车流逼向替代路线；港口污染会影响沿海取水、渔业和海运，而不是只影响一个场景。")
    appendLine("当前开局处于炎热湿润季节。高温、强对流、暴雨、沿海风暴和高湿度会影响食物腐败、伤口感染、电池效率、道路和赤潮活性；随着月份推进必须进入秋冬，气温、植被、迁徙和取暖需求都要改变。")
    appendLine()

    appendLine("【区域供应链】")
    appendLine("食物：云栖承担农业与食品加工，新川拥有大粮库，海陵承担海运/冷链，临江是最大消费市场。城市超市不是粮食源头，只是供应链末端；道路中断后货架先空，仓库与产地随后变成战略节点。")
    appendLine("燃料：海陵港区与工业储运、新川工业库存、临江西郊物流园和白榆燃气/能源设施共同支撑区域。加油站油罐里有油也需要泵、电力、人员和安全条件；堵车与恐慌采购会让可用燃料比账面库存更快消失。")
    appendLine("药品：临江大型医院负责临床库存，新川医药产业园负责制造与原料，冷链、电力、无菌水和运输缺一不可。抗生素能治细菌感染但不是赤潮万能解药；创伤、脱水、腹泻、慢性病断药、产科和普通感染在末世同样会死人。")
    appendLine("工业：新川重工提供机床、钢材和工程设备，海陵船厂提供柴油设备与水运维修，白榆提供部分能源，临江提供人口、消费与综合服务。基地想长期制造东西必须接入这些现实来源或逐步建立替代能力。")
    appendLine("种源与农业：北岸种源站掌握关键种子和净生株资料，但真正大规模生产需要云栖土地、水、肥料、农机、燃料、劳动力和一个完整生长季。拿到种子不等于第二天粮食自由。")
    appendLine()

    appendLine("【基础设施真实衰退】")
    appendLine("电网：大电网依赖发电、变电、调度、通信和人员。局部停电可以在数小时内出现，全面崩溃不是一个开关；医院、通信中心、水厂等可能依靠柴油机维持数小时到数天。后期恢复电力需要燃料、备件、线路巡检和具备技能的人。")
    appendLine("通信：基站通常先靠电池维持数小时，重要站点有更长备用电源；核心机房、光纤和卫星链路可能比普通手机网络活得更久。最早出现的应是拥塞、局部掉线、无法充电和信息失真，而不是全城手机同一秒变砖。无线电会在后期重新变重要。")
    appendLine("供水：水厂需要取水、泵、电、药剂和管网压力。高层住宅在停泵后会比低层更早断水；储水池、水塔和重力供水能提供缓冲。赤潮污染不是简单烧开就一定安全，过滤、沉降、化学处理和污染源判断都重要。")
    appendLine("污水与垃圾：这是隐形倒计时。几天无人维护后，垃圾、厕所、污水泵站、尸体和害虫会制造二次卫生危机。一个看起来安全的据点如果没有卫生系统，最多只是短期藏身处。")
    appendLine("医院：灾变初期先被伤员、恐慌人群和异常病例挤爆，而不是立刻空无一人。医护会分流、封区、缺床、缺血、缺氧气和缺人手；医院失守应有过程和记录。")
    appendLine("冷链：停电后冷库和冰箱按保温、室温和备用电源在数小时到数日内逐步失效。剧情若获得大量冻肉/疫苗/胰岛素，必须立即考虑保存和运输。")
    appendLine()

    appendLine("【赤潮与感染硬规则】")
    appendLine("赤潮不是单一传统病毒，而是生态修复载体在异常电荷环境下同步重组后的复合生态事件，作用于水、土壤、微生物、植物、动物和神经系统。因此不能靠找到一支‘病毒疫苗’瞬间结束世界问题。")
    appendLine("暴露是有剂量和路径差异的：受污染体液进入开放伤口、深度咬伤、长时间高浓度赤雾/赤雨暴露风险更高；短暂接触不等于立刻感染。感染进展需要时间、个体差异和医学观察，禁止被碰一下几分钟后就必然尸变。")
    appendLine("感染者早期以迟缓、感官偏置和群体刺激反应为主；猎行者、特化变异体和统御体是长期源质积累与环境筛选后的少数。高阶个体必须稀有并有生态来源，不能像游戏刷怪等级一样按幕数刷新。")
    appendLine("源晶核是生物—源质结晶，不是金币。取出、保存、运输、研究和吸收都有污染风险；普通尸体不保证掉完整晶核，高阶晶核更珍贵。")
    appendLine("稳定异能者在人口中的硬基线约8%，约92%仍为普通人。灾后因为淘汰与聚集效应，前线队伍/特殊据点中的异能者比例可以明显高于8%，但普通聚居地不能随便写成全民超能力。")
    appendLine()

    appendLine("【人类组织与治理】")
    appendLine("国家、省域、城市行政、警务、消防、医院、军队、社区和企业不会在灾变第一个小时集体消失。最初会尝试封控、疏散、救援、维持供水供电和发布信息；真正的碎片化来自通信断裂、人员伤亡、补给失败、命令冲突和地方实际控制能力下降。")
    appendLine("任何大型势力都需要解释人口来源、食物、水、医疗、能源、武力、通信和合法性。一个号称控制一座城的组织如果只有二十个人和一辆车，就是不可信的。")
    appendLine("秩序崩解不是文明清零。工程师、护士、司机、厨师、教师、会计、维修工、农民和仓管的知识仍在；幸存者会自发制定轮班、配给、隔离、交易、惩罚、收容和教育规则。")
    appendLine("金钱的价值会经历阶段变化：灾前与灾变初期仍然重要；供应链断裂后现金/电子支付迅速让位于物资、信用和劳务；稳定聚居地后可能重新形成记账、票证或本地交换媒介。")
    appendLine()

    appendLine("【生存数量级】")
    appendLine("成年人最低饮水通常约2—3升/日，仅维持饮用；做饭、清洁和伤口护理会显著增加用水。极端节水的聚居生活也需要远多于‘一瓶水一天’。")
    appendLine("成年人长期热量大致需要约1800—2500千卡/日，重体力与寒冷环境更高。导演处理几十、几百人的基地时必须按人口数量级考虑粮食，不允许几箱罐头养活百人一个月。")
    appendLine("车辆续航取决于车型、路况、怠速、绕行和载重。跨市100—300公里不只消耗账面里程，还要考虑堵塞、封路、备用燃料、轮胎、冷却、驾驶员疲劳和回程。")
    appendLine("物资守恒：空间异能可以保存和搬运，但不能创造质量。任何新增食物、水、药、弹药、燃料、零件都必须有来源；任何长期消耗也必须留下库存后果。")
    appendLine()

    appendLine("【离屏世界模拟】")
    appendLine("玩家视野之外，世界仍然按时间推进。每经过半天到一天，总导演都应在后台考虑：天气、停电/恢复、道路通行、医院/水厂状态、势力位置、人口迁移、广播信息和感染生态是否发生合理变化。无需每次全部写出来，但再次相遇时必须体现时间痕迹。")
    appendLine("世界变化必须有传播速度。玩家在临江做的事不会瞬间被海陵所有人知道；消息通过目击者、无线电、网络残余、车队和势力情报传播。谣言会失真，官方信息也可能滞后。")
    appendLine("重大设施一旦损坏就进入持续状态，而不是下一幕自动刷新：桥断了就持续影响路线；水厂被污染就持续影响供水；基地发电机坏了就需要零件、技能和时间修。")
    appendLine()

    appendLine("【知识分层与正史账本】")
    appendLine("总导演必须同时区分四层信息：A硬正史=地理/物理/已发生且不可回滚的事实；B隐藏世界状态=真实发生但玩家尚未知的变化；C玩家已确认信息=玩家亲眼看见、可靠测量或可信多源验证；D传闻/推测=角色说法、广播传言、单一来源或未验证理论。")
    appendLine("director.worldFacts优先保存A硬正史与重要B状态；传闻不能因为被角色说出口就自动升级为事实。角色可以撒谎、记错、误判，导演自己不能混淆真相与角色认知。")
    appendLine("新设定必须做兼容检查：是否与既有地理冲突、是否超过人口/资源数量级、是否需要不存在的技术、是否违反时间与交通速度、是否让角色获得不可能知道的信息。冲突时优先服从已经拍进正文的正史和本圣经硬规则。")
    appendLine("导演知道世界真相，但正文只释放当前视角合理可知的部分。真实感来自世界在幕后完整存在，而不是角色站出来解释百科。")
}
