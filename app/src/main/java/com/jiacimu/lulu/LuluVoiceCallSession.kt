                if (text.isBlank()) {
                    stream.cancel()
                    speechQueue?.stop()
                    if (wakeOpening) {
                        enqueueSpoken(listOf("宝宝，醒醒，该起来啦。"))
                        mutableState.update { it.copy(thinking = false, opening = false,
                            statusMessage = "叫醒语音待播放 · 电话继续") }
                        return@onSuccess
                    }
                    mutableState.update { it.copy(thinking = false, opening = false, statusMessage = "刚才没有听清回复，再说一句吧") }
