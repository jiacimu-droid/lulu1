                // an invited bedtime reply uses the bedtime voice in this same turn.
                if (!wakeOpening && !autonomousSleep && !autonomousSilence) when (reply.sleepDecision) {
                    "enable" -> setSleepMode(true)
                    "disable" -> setSleepMode(false)
                }
