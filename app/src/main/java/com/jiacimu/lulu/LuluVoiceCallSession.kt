    fun onLive2DTouch(characterId: String, callId: String,
        region: String, gesture: String, force: Float = .55f,
        durationMillis: Long = 0L): Boolean {
        val call = mutableState.value
        if (!call.connected || !LuluCallWindowController.videoRequested.value ||
            call.characterId != characterId || call.callExperienceId != callId ||
            !InteractionSignalBridge.hasRenderedVideo(characterId, callId) ||
            Live2DTouchZones.label(region) == null ||
            !force.isFinite() || force !in .1f..1f || durationMillis < 0 ||
            gesture !in setOf("tap", "hold", "stroke", "stroke-left",
                "stroke-right", "stroke-up", "stroke-down",
                "kiss", "slap", "slap-left", "slap-right")) return false
        if (touchBatchRole != characterId || touchBatchCall != callId) {
            touchBatchJob?.cancel()
            touchBatch.clear()
            touchBatchRole = characterId
            touchBatchCall = callId
        }
        touchBatch += Live2DTouchContact(region, gesture, force, durationMillis)
        val earlierGeneration = replyGeneration
        touchBatchJob?.cancel()
        touchBatchJob = scope.launch {
            delay(950L)
            if (!mutableState.value.connected ||
                mutableState.value.callExperienceId != callId ||
                mutableState.value.characterId != characterId) {
                touchBatch.clear()
                return@launch
            }
            val grouped = touchBatch.toList()
            touchBatch.clear()
            if (grouped.isEmpty()) return@launch
            val id = InteractionSignalBridge.recordAvatarTouches(
                characterId, callId, grouped.map { it.region to it.gesture },
                forces = grouped.map { it.force },
                durationsMillis = grouped.map { it.durationMillis })
                ?: return@launch
            // New user speech owns the reply; don't interrupt to repeat it.
            if (replyGeneration == earlierGeneration && !confirmedSpeechInProgress()) {
                onExternalToolResult(characterId, callId, id)
            }
        }
        return true
    }

    fun isActiveForChat(conversationId: String): Boolean {
        val call = mutableState.value
        return call.connected && call.conversationId == conversationId
    }

    fun onTextChatMessage(conversationId: String, content: String, evidenceId: String): Boolean {
        if (!isActiveForChat(conversationId) || content.isBlank()) return false
        val callId = mutableState.value.callExperienceId
        incomingChatDrafts.add(content.trim())
        incomingChatEvidenceIds.add(evidenceId)
        incomingChatJob?.cancel()
        incomingChatJob = scope.launch {
            // A cluster of QQ chat bubbles is one human turn, not N rapid phone replies.
            delay(1_600L)
            while (isActiveForChat(conversationId) && mutableState.value.callExperienceId == callId &&
                mutableState.value.opening) delay(250L)
            if (!isActiveForChat(conversationId) || mutableState.value.callExperienceId != callId) return@launch
            val typed = incomingChatDrafts.joinToString("\n").trim()
            val evidenceIds = incomingChatEvidenceIds.toList()
            incomingChatDrafts.clear()
            incomingChatEvidenceIds.clear()
            if (typed.isBlank()) return@launch
            handleUserSpeech(typed, allowWhileMuted = true, alreadyPersisted = true,
                persistedUserEvidenceIds = evidenceIds)
        }
        return true
    }
