                    } else if (receipt.startsWith("已登记")) {
                        mutableState.update { it.copy(statusMessage = "音乐任务已登记，等待实际播放") }
                    }
                }
                appContext?.let {
                    com.jiacimu.lulu.data.DeferredCallMediaAction.chooseAfterSpeech(
                        latest.characterId, latest.callExperienceId,
