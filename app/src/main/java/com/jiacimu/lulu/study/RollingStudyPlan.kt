    fun itemsFor(date: LocalDate): List<StudyPlanItem> = buildList {
        monthly[YearMonth.from(date)]?.let { (title, tasks) ->
            add(
                StudyPlanItem(
                    id = "rolling:month:${YearMonth.from(date)}",
                    range = StudyPlanRange.Monthly,
                    title = title,
                    note = tasks.joinToString("\n") { "• $it" },
                ),
            )
        }
        weekly.firstOrNull { date in it.start..it.end }?.let { week ->
            add(
                StudyPlanItem(
                    id = "rolling:week:${week.start}",
                    range = StudyPlanRange.Weekly,
                    title = week.title,
                    note = week.tasks.joinToString("\n") { "• $it" },
                ),
            )
        }
    }

