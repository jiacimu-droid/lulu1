/**
 * User-approved postgraduate exam plan.
 *
 * The plan deliberately exposes a weekly task pool instead of a clock-by-clock timetable:
 * - 4h/day is the low-energy floor, 5h/day is the normal planning baseline, 6h/day is stretch capacity.
 * - Professional law courses are P0 until the regular new-course line is closed.
 * - English is optional recovery work when professional-course concentration drops.
 * - Politics has no fixed slot before 2026-10-15.
 */
internal object RollingStudyPlan {
    private data class Window(
        val start: LocalDate,
        val end: LocalDate,
        val title: String,
        val tasks: List<String>,
    )

    fun itemsFor(date: LocalDate): List<StudyPlanItem> = buildList {
        monthly[YearMonth.from(date)]?.let { (title, tasks) ->
            add(
                StudyPlanItem(
                    id = "rolling:month:${YearMonth.from(date)}",
                    range = StudyPlanRange.Monthly,
                    title = title,
                    note = tasks.joinToString("\n") { "• $it" },
                ),
            )
        }
        weekly.firstOrNull { date in it.start..it.end }?.let { week ->
            add(
                StudyPlanItem(
                    id = "rolling:week:${week.start}",
                    range = StudyPlanRange.Weekly,
                    title = week.title,
                    note = week.tasks.joinToString("\n") { "• $it" },
                ),
            )
        }
    }

