/**
 * Small, original texts shipped with the app. These are fictional books, not
 * events in the companion's real digital world. Used only when the user's
 * library and theater chapters provide no readable text.
 *
 * Progress is persisted per character by ReadingBackgroundBridge exactly as
 * for uploaded books; the model receives the actual next excerpt, never an
 * invented title or imagined continuation.
 */
internal object ReadingStarterLibrary {
    fun books(): List<BackgroundReadingBook> = listOf(
        BackgroundReadingBook(
            id = "starter:the-last-lamp",
            title = "《最后一盏灯》",
            source = "内置原创短篇",
            content = """
                旧港镇的夜间电车在冬天停运了。停运告示贴在玻璃窗上，纸角卷起，却始终没有人来撕。每天傍晚，站台还是会亮起七盏灯；第一盏照着售票亭，最后一盏照着一张面朝海的长椅。
                
                阮青在最后一盏灯下等了六天。第七天来的不是电车，而是一个提着黄色工具箱的年轻人。他抬头看了一眼灯，说：“这里不是早就停电了吗？”
                
                阮青不回答。他也不追问，跪下来拆开灯柱底座。电线确实没有接入电网，却沿着地面伸进站台后的旧仓库。仓库门锁生了锈，门内传出极轻的钟摆声。
                
                工具箱里没有万能钥匙。年轻人用一根废铁丝折腾了很久，终于把锁芯拨开。仓库里没有人，只有一排旧录音机、一块落满灰的车次牌，还有一个用黄胶带缠着的盒子。盒子旁边贴着字条：“最后一趟车不收车票，只收还没说出口的话。”
                
                阮青这才走进来，指着最上面一台录音机：“我母亲以前在这里报站。十年前，码头失火，她在通知乘客撤离时失了踪。我一直以为她说完最后一句，就没机会再说别的话了。”
                
                年轻人没有去碰那台录音机。他先把盒子打开，里面整齐放着几十张没有寄出的明信片。每张都写着相同的落款：“旧港站，值班室。”
                
                阮青翻到第十四张，上面写的是：“今天雨太大。小青又忘记带伞。她已经长大了，但我还是想站在门口等她一会儿。”
                
                这些字并不能证明母亲后来去了哪里。它们也没有解释那场火。阮青在地上坐下来，忽然发现自己一直要找的不是一个确定的答案，而是母亲并不只活在那场灾难最后一刻的证据。
                
                年轻人把仓库的总电闸按下，七盏灯一盏接一盏灭了。原来它们连着一组早已失效的备用电池；是有人偷偷修复了线路，每晚从仓库里手动供电。
                
                他在维修记录上看到一个名字——余舟，五十六岁，旧港站最后一任驾驶员。备注栏里写着：“给等车的人留一盏灯。”这行字的日期，是三天以前。
                
                阮青站到第七盏灯下时，灯已经不亮了。海风吹得车次牌微微晃动，她把那张明信片收进口袋，决定明早去问一问余舟。她终于有了一个新的、可以走过去寻找的地方。
            """.trimIndent(),
        ),
        BackgroundReadingBook(
            id = "starter:glass-sea",
            title = "《玻璃海来信》",
            source = "内置原创短篇",
            content = """
                城市北边有一家修理失物的小店。店主收手表、收打火机、收裂开一角的八音盒，却不接手机。他说手机里的东西太多，修一块屏幕只要半小时，修好一个人对屏幕的期待却可能要很久。
                
                春天的一个下午，一个女孩送来一只密封的玻璃瓶。瓶身完好，里面有一张湿透的纸，墨迹已经模糊得只剩一圈圈蓝色。她希望店主帮她辨认上面的字。
                
                “这不是修理，”店主说，“这是猜。”
                
                女孩把瓶子留在柜台上，说：“那就请你先不要猜。我晚上来取。”
                
                店主用最细的镊子把纸夹出来，在干净的木板上铺平。他发现纸不是被海水泡过，而是沾了一层含糖的透明液体。信纸背面压着一个很浅的印章：玻璃海观测站。
                
                镇上的玻璃海不是真正的海，是一座废弃温室。过去这里曾养过上万只透明水母，屋顶的巨大玻璃在夏日把池水照成海一样的颜色。观测站在二十年前关门，后来改成了仓库。
                
                店主骑车去了那里。温室门口长着野草，里面有人正在拆除最后几排水箱。看门人说，前几天确实有个穿蓝色雨衣的人进来找东西，出来时手里拿着一只玻璃瓶。
                
                “她找到了吗？”店主问。
                
                看门人说不知道。一个人有没有找到想找的东西，不能只凭她走出来时是不是笑着判断。
                
                店主回店时，女孩已经在门口等了。他拿出一张复印的观测站旧平面图，告诉她印章的来源，也告诉她那封信恐怕无法还原。他没有替她补上一个温柔的结局。
                
                女孩看着图上标出的旧水母池，说那只瓶子是父亲留下的。父亲从不讲年轻时的事情，却偶尔会在厨房的灯下画一些圆形的东西。她一直以为那是星星。
                
                店主把信纸重新封进瓶子，给她一张干燥剂使用说明，又把观测站的位置圈出来。女孩握着玻璃瓶站了片刻，问：“如果那里也什么都没有呢？”
                
                “那就知道那里什么都没有，”店主说，“这也是你自己走过去得到的答案。”
                
                晚上关店时，他在账本的维修项目里写下：“一只瓶子，未修复；一段路径，已确认。”那是他开店以来第一张没有收费的收据。
            """.trimIndent(),
        ),
    )
}
